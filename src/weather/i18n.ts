export function weatherLanguage(language = 'en'): string {
  const code = languageOf(language);
  return Object.hasOwn(TEXT, code) ? code : 'en';
}

// A language's text by key, with its compass points and its words for today and now.
export interface WeatherText {
  (key: TextKey): string;
  compass: string[];
  today: string;
  now: string;
}
const capitalize = (text: string, locale: string) =>
  text ? text.charAt(0).toLocaleUpperCase(locale) + text.slice(1) : text;
export function weatherText(language: string): WeatherText {
  const code = weatherLanguage(language),
    values = TEXT[code] ?? TEXT.en,
    compass = (COMPASS[code] ?? COMPASS.en).split(' ');
  let relative: Intl.RelativeTimeFormat;
  try {
    relative = new Intl.RelativeTimeFormat(language, { numeric: 'auto' });
  } catch {
    relative = new Intl.RelativeTimeFormat('en', { numeric: 'auto' });
  }
  const t = (key: TextKey) => values[KEYS.indexOf(key)] ?? TEXT.en[KEYS.indexOf(key)] ?? key,
    // The locale Intl settled on: a tag it can't read (en_US) would make casing throw.
    { locale } = relative.resolvedOptions();
  return Object.assign(t, {
    compass,
    today: capitalize(relative.format(0, 'day'), locale),
    now: capitalize(relative.format(0, 'second'), locale),
  });
}
